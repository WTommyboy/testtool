import type { ParsedBug, ParsedResultCase } from "./result-xlsx-parser";

export type GeneratedBugCandidate = ParsedBug & {
  autoGeneratedFromFail: boolean;
  sourceStatus: string;
};

type MissingBugCandidateInput = {
  cases: ParsedResultCase[];
  bugs: ParsedBug[];
  defaultBugRelatedCaseNo?: string | null;
};

const AUTO_BUG_SEVERITY = "P2";

export const normalizeResultCaseNo = (value: string | null | undefined): string =>
  (value ?? "")
    .trim()
    .replace(/\s+/g, "")
    .replace(/^DEMO-/i, "")
    .toUpperCase();

const normalizedStatus = (value: string | null | undefined): string =>
  (value ?? "").trim().toUpperCase().replace(/\s+/g, "_");

const safeIdPart = (value: string): string => value.replace(/[^a-zA-Z0-9._-]+/g, "-").replace(/^-+|-+$/g, "") || "UNKNOWN";

const stringifyValue = (value: unknown): string | null => {
  if (value === null || value === undefined) return null;
  if (typeof value === "string") return value.trim() || null;
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  try {
    return JSON.stringify(value);
  } catch {
    return String(value);
  }
};

const firstDetailText = (detail: Record<string, unknown> | null, keys: string[]): string | null => {
  if (!detail) return null;
  for (const key of keys) {
    const value = stringifyValue(detail[key]);
    if (value) return value;
  }
  return null;
};

const truncate = (value: string, maxLength: number): string => {
  if (value.length <= maxLength) return value;
  return `${value.slice(0, Math.max(0, maxLength - 3))}...`;
};

const truthyMarker = (value: unknown): boolean => {
  if (value === true) return true;
  if (typeof value !== "string") return false;
  return /^(true|yes|y|1|是|需追蹤|需要追蹤|追蹤|需開bug|需要開bug|bug)$/i.test(value.trim());
};

const blockedExplicitlyRequestsDefectTracking = (detail: Record<string, unknown> | null): boolean => {
  if (!detail) return false;
  return [
    "需追蹤缺陷",
    "需要追蹤缺陷",
    "需開Bug",
    "需要開Bug",
    "bug_candidate",
    "shouldTrackDefect",
    "track_defect",
    "create_bug"
  ].some((key) => truthyMarker(detail[key]));
};

const bugRelatedCaseNo = (bug: ParsedBug, defaultBugRelatedCaseNo: string | null): string | null => {
  const explicit = bug.relatedCaseNo?.trim();
  if (explicit) return explicit;
  return defaultBugRelatedCaseNo?.trim() || null;
};

const existingBugCaseKeys = (bugs: ParsedBug[], defaultBugRelatedCaseNo: string | null): Set<string> => {
  const keys = new Set<string>();
  for (const bug of bugs) {
    const key = normalizeResultCaseNo(bugRelatedCaseNo(bug, defaultBugRelatedCaseNo));
    if (key && key !== "-") keys.add(key);
  }
  return keys;
};

const shouldGenerateForCase = (item: ParsedResultCase): boolean => {
  const status = normalizedStatus(item.status);
  if (status === "FAIL") return true;
  if (status === "BLOCKED") return blockedExplicitlyRequestsDefectTracking(item.detailJson);
  return false;
};

export const buildGeneratedBugCandidate = (item: ParsedResultCase): GeneratedBugCandidate => {
  const status = normalizedStatus(item.status);
  const detail = item.detailJson;
  const autoGeneratedFromFail = status === "FAIL";
  const marker = autoGeneratedFromFail ? "auto_generated_from_fail=true" : "auto_generated_from_blocked_defect=true";
  const reason =
    firstDetailText(detail, ["錯誤原因", "blocked_reason", "實際行為", "問題", "結論"]) ??
    item.verdictReason ??
    item.caseTitle ??
    `${item.caseNo} ${status}`;
  const title = `[AUTO] ${item.caseNo} ${truncate(reason, 90)}`;
  const rdDispatch = firstDetailText(detail, ["RD 分派", "RD分派", "rd_dispatch", "rdDispatch"]);
  const lines = [
    title,
    marker,
    "source=result_xlsx_ingest_fallback",
    `case_no=${item.caseNo}`,
    item.caseTitle ? `case_title=${item.caseTitle}` : null,
    `status=${status}`,
    item.verdictReason ? `fail_category=${item.verdictReason}` : null,
    firstDetailText(detail, ["測試目的"]) ? `測試目的: ${firstDetailText(detail, ["測試目的"])}` : null,
    firstDetailText(detail, ["設定條件"]) ? `設定條件: ${firstDetailText(detail, ["設定條件"])}` : null,
    firstDetailText(detail, ["預期行為"]) ? `預期行為: ${firstDetailText(detail, ["預期行為"])}` : null,
    firstDetailText(detail, ["實際行為"]) ? `實際行為: ${firstDetailText(detail, ["實際行為"])}` : null,
    firstDetailText(detail, ["錯誤原因"]) ? `錯誤原因: ${firstDetailText(detail, ["錯誤原因"])}` : null,
    firstDetailText(detail, ["根因層級"]) ? `根因層級: ${firstDetailText(detail, ["根因層級"])}` : null,
    firstDetailText(detail, ["驗證方法"]) ? `驗證方法: ${firstDetailText(detail, ["驗證方法"])}` : null,
    rdDispatch ? `RD 分派: ${rdDispatch}` : null,
    item.detailParseError ? `detail_json_parse_error=${item.detailParseError}` : null,
    !detail && item.detailJsonRaw ? `detail_json_raw=${truncate(item.detailJsonRaw, 500)}` : null
  ].filter((line): line is string => Boolean(line));

  return {
    severity: AUTO_BUG_SEVERITY,
    bugId: `AUTO-${safeIdPart(item.caseNo)}`,
    relatedCaseNo: item.caseNo,
    title,
    description: lines.join("\n"),
    suggestion: [
      "Server generated this fallback candidate because result.xlsx contained a tracked defect status without a corresponding Bug sheet row.",
      autoGeneratedFromFail ? "Replace it with a Codex-authored Bug row on rerun when possible." : "BLOCKED cases only generate this candidate when detail_json explicitly requests defect tracking.",
      rdDispatch ? `Suggested RD dispatch: ${rdDispatch}.` : null
    ].filter((line): line is string => Boolean(line)).join(" "),
    status: "OPEN",
    autoGeneratedFromFail,
    sourceStatus: status
  };
};

export const buildMissingBugCandidates = ({
  cases,
  bugs,
  defaultBugRelatedCaseNo = null
}: MissingBugCandidateInput): GeneratedBugCandidate[] => {
  const existingCaseKeys = existingBugCaseKeys(bugs, defaultBugRelatedCaseNo);
  const candidates: GeneratedBugCandidate[] = [];
  for (const item of cases) {
    if (!shouldGenerateForCase(item)) continue;
    const key = normalizeResultCaseNo(item.caseNo);
    if (!key || existingCaseKeys.has(key)) continue;
    const candidate = buildGeneratedBugCandidate(item);
    candidates.push(candidate);
    existingCaseKeys.add(key);
  }
  return candidates;
};
